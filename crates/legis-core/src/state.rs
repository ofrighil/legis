impl FromStr for State {
    type Err = StateError;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        Self::ALL
            .into_iter()
            .find(|state| state.code() == s || state.name() == s)
            .ok_or_else(|| StateError(s.to_owned()))
    }
}
